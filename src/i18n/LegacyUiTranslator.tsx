const ORIGINAL_TEXT = new WeakMap<Text, string>();
const ORIGINAL_ATTRS = new WeakMap<Element, Map<string, string>>();
const TRACKED_TEXT = new Set<Text>();
const TRACKED_ELEMENTS = new Set<Element>();
const ATTRS = ["title", "placeholder", "aria-label", "alt"] as const;

function shouldSkip(node: Node): boolean {
  const element = node instanceof Element ? node : node.parentElement;
  return !element || Boolean(element.closest("[data-i18n-skip],script,style,code,pre,textarea"));
}

function translateNodeValue(node: Text, source: string): string {
  // "Nặng" vừa là nhãn thuế nặng vừa là tiền tố trọng lượng trang bị.
  // Nút trong thanh thuế dùng nghĩa đầu; các vị trí còn lại dùng nghĩa trọng lượng.
  if (source.trim() === "Nặng" && node.parentElement?.closest("button")) {
    return source.replace("Nặng", "重税");
  }
  return translateLegacyZh(source);
}

function translateTextNode(node: Text): void {
  if (shouldSkip(node)) return;
  if (!ORIGINAL_TEXT.has(node)) {
    const translated = translateNodeValue(node, node.data);
    if (translated === node.data) return;
    ORIGINAL_TEXT.set(node, node.data);
    TRACKED_TEXT.add(node);
    node.data = translated;
    return;
  }
  node.data = translateNodeValue(node, ORIGINAL_TEXT.get(node) ?? node.data);
}

function translateElementAttrs(element: Element): void {
  if (shouldSkip(element)) return;
  let originals = ORIGINAL_ATTRS.get(element);
  for (const attr of ATTRS) {
    const value = element.getAttribute(attr);
    if (!value) continue;
    const translated = translateLegacyZh(value);
    if (!originals?.has(attr) && translated === value) continue;
    if (!originals) {
      originals = new Map();
      ORIGINAL_ATTRS.set(element, originals);
      TRACKED_ELEMENTS.add(element);
    }
    if (!originals.has(attr)) originals.set(attr, value);
    element.setAttribute(attr, translateLegacyZh(originals.get(attr) ?? value));
  }
}

function translateTree(root: Node): void {
  if (root instanceof Text) {
    translateTextNode(root);
    return;
  }
  if (!(root instanceof Element) && !(root instanceof Document)) return;
  if (root instanceof Element) translateElementAttrs(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  let current = walker.nextNode();
  while (current) {
    if (current instanceof Text) translateTextNode(current);
    else if (current instanceof Element) translateElementAttrs(current);
    current = walker.nextNode();
  }
}

function restoreOriginals(): void {
  for (const node of TRACKED_TEXT) {
    const original = ORIGINAL_TEXT.get(node);
    if (original !== undefined && node.isConnected) node.data = original;
    ORIGINAL_TEXT.delete(node);
  }
  for (const element of TRACKED_ELEMENTS) {
    const originals = ORIGINAL_ATTRS.get(element);
    if (!originals || !element.isConnected) continue;
    for (const [attr, value] of originals) element.setAttribute(attr, value);
    ORIGINAL_ATTRS.delete(element);
  }
  TRACKED_TEXT.clear();
  TRACKED_ELEMENTS.clear();
}

export function LegacyUiTranslator(): null {
  const language = useSettingsStore((state) => state.language);

  useEffect(() => {
    // Theo dõi body để bao phủ cả Modal dùng portal nằm ngoài #root.
    const root = document.body;
    if (!root) return;
    if (language !== "zh-CN") {
      restoreOriginals();
      return;
    }

    translateTree(root);
    const observer = new MutationObserver((mutations) => {
      observer.disconnect();
      for (const mutation of mutations) {
        if (mutation.type === "characterData" && mutation.target instanceof Text) {
          if (ORIGINAL_TEXT.has(mutation.target)) ORIGINAL_TEXT.set(mutation.target, mutation.target.data);
          translateTextNode(mutation.target);
        }
        if (mutation.type === "attributes" && mutation.target instanceof Element && mutation.attributeName) {
          const originals = ORIGINAL_ATTRS.get(mutation.target);
          const value = mutation.target.getAttribute(mutation.attributeName);
          if (originals?.has(mutation.attributeName) && value !== null) originals.set(mutation.attributeName, value);
          translateElementAttrs(mutation.target);
        }
        for (const node of mutation.addedNodes) translateTree(node);
      }
      observer.observe(root, {
        subtree: true,
        childList: true,
        characterData: true,
        attributes: true,
        attributeFilter: [...ATTRS],
      });
    });
    observer.observe(root, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: [...ATTRS],
    });
    return () => observer.disconnect();
  }, [language]);

  return null;
}
