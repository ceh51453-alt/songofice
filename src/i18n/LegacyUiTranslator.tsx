  translated = translated.replace(/(\d[\d.,]*)\s*người/g, "$1 人");
  translated = translated.replace(/(\d[\d.,]*)\s*đề nghị/g, "$1 项提议");
  translated = translated.replace(/(\d[\d.,]*)\s*lãnh địa/g, "$1 个领地");
